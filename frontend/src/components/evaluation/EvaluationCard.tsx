import type { Evaluation } from '../../types';
import ScoreRing from '../ui/ScoreRing';
import RecommendationBadge from '../ui/RecommendationBadge';
import { CheckCircle, XCircle, Lightbulb, Brain, AlertTriangle, Info } from 'lucide-react';

interface Props {
  evaluation: Evaluation;
}

export default function EvaluationCard({ evaluation }: Props) {
  if (evaluation.error) {
    return (
      <div className="card p-6 border-rose-100">
        <div className="flex items-center gap-3 text-rose-600">
          <AlertTriangle className="w-5 h-5" />
          <p className="text-sm font-semibold">Evaluation failed: {evaluation.error}</p>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-6 animate-fade-in">
      {/* AI Disclaimer */}
      <div className="flex items-start gap-3 p-4 bg-primary-50 rounded-xl border border-primary-100">
        <Brain className="w-5 h-5 text-primary-500 flex-shrink-0 mt-0.5" />
        <div>
          <p className="text-xs font-semibold text-primary-700">AI-Assisted Evaluation</p>
          <p className="text-xs text-primary-600 mt-0.5">
            Generated by Google Gemini AI. This evaluation is advisory and should not replace expert human judgment.
          </p>
        </div>
      </div>

      {/* Summary */}
      {evaluation.summary && (
        <div className="card p-5">
          <div className="flex items-center gap-2 mb-3">
            <Info className="w-4 h-4 text-slate-400" />
            <h3 className="text-sm font-bold text-slate-700">Summary</h3>
          </div>
          <p className="text-sm text-slate-600 leading-relaxed">{evaluation.summary}</p>
        </div>
      )}

      {/* Score Rings */}
      <div className="card p-6">
        <h3 className="section-title mb-6">Evaluation Scores</h3>
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-8 justify-items-center">
          <ScoreRing score={evaluation.novelty_score}      label="Novelty"      />
          <ScoreRing score={evaluation.methodology_score}  label="Methodology"  />
          <ScoreRing score={evaluation.feasibility_score}  label="Feasibility"  />
          <ScoreRing score={evaluation.clarity_score}      label="Clarity"      />
        </div>
        <div className="mt-6 pt-5 border-t border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <p className="text-xs text-slate-500">Overall Score</p>
            <p className="text-3xl font-bold text-primary-600 mt-0.5">
              {evaluation.overall_score}
              <span className="text-base text-slate-400 font-normal"> / 10</span>
            </p>
            <p className="text-sm text-slate-500 mt-0.5">{evaluation.overall_percentage}%</p>
          </div>
          <RecommendationBadge recommendation={evaluation.overall_recommendation} />
        </div>
      </div>

      {/* Strengths / Weaknesses / Suggestions */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        <ListCard
          title="Strengths"
          items={evaluation.strengths}
          icon={<CheckCircle className="w-4 h-4 text-emerald-500" />}
          color="emerald"
        />
        <ListCard
          title="Weaknesses"
          items={evaluation.weaknesses}
          icon={<XCircle className="w-4 h-4 text-rose-500" />}
          color="rose"
        />
        <ListCard
          title="Suggestions"
          items={evaluation.suggestions}
          icon={<Lightbulb className="w-4 h-4 text-amber-500" />}
          color="amber"
        />
      </div>
    </div>
  );
}

function ListCard({ title, items, icon, color }: {
  title: string; items: string[]; icon: React.ReactNode; color: 'emerald' | 'rose' | 'amber';
}) {
  const bg = { emerald: 'bg-emerald-50', rose: 'bg-rose-50', amber: 'bg-amber-50' }[color];
  const text = { emerald: 'text-emerald-700', rose: 'text-rose-700', amber: 'text-amber-700' }[color];
  const bullet = { emerald: 'bg-emerald-300', rose: 'bg-rose-300', amber: 'bg-amber-300' }[color];

  return (
    <div className={`rounded-2xl p-5 ${bg}`}>
      <div className="flex items-center gap-2 mb-3">
        {icon}
        <h4 className={`text-sm font-bold ${text}`}>{title}</h4>
      </div>
      <ul className="space-y-2">
        {items.map((item, i) => (
          <li key={i} className="flex items-start gap-2 text-xs text-slate-600">
            <span className={`w-1.5 h-1.5 rounded-full ${bullet} flex-shrink-0 mt-1.5`} />
            {item}
          </li>
        ))}
      </ul>
    </div>
  );
}
